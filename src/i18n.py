def translate(text, lang):
    if lang == 'pl':
        return TRANSLATIONS.get(text, text)
    return text


def js_translations(lang):
    if lang != 'pl':
        return {}
    return {key: TRANSLATIONS[key] for key in JS_STRING_KEYS if key in TRANSLATIONS}
